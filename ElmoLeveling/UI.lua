function U.Update()
    if not U.panel then return end
    U.progress = U.ReadProgress()
    local progress = U.progress
    U.level:SetText(progress.level > 0 and progress.level or "?")
    U.percent:SetText(progress.capped and "MAX" or (progress.fraction and (math.floor(progress.fraction * 100) .. "%") or "--"))
    U.nextLevel:SetText(progress.remaining and ("|cffc198f3" .. U.Number(progress.remaining) .. " XP|r to level " .. (progress.level + 1)) or U.ProgressText())
    U.RefreshRing(progress)
    U.fullZone = locationName(GetRealZoneText) or locationName(GetZoneText) or "Location unavailable"
    U.fullSubzone = locationName(GetSubZoneText)
    if not U.fullSubzone or U.fullSubzone == U.fullZone then U.fullSubzone = locationName(GetMinimapZoneText) end
    if not U.fullSubzone or U.fullSubzone == U.fullZone then U.fullSubzone = "" end
    U.zone:SetText(U.fullZone); U.subzone:SetText(U.fullSubzone)
    U.character:SetText(A.Text(A.Call(UnitName, "player")) or "Player")
    U.rested:SetText(progress.rested and (math.floor(progress.rested * 100 + .5) .. "% rested") or "Rested --")
    fitClock(U.timeValue, U.Clock(A.Stats().elapsed))
    local bags = A.Bags.state
    U.freeSlots:SetText(bags and bags.freeKnown and (bags.free .. " free slots") or "Bag space --")
    U.freeSlots:SetTextColor(unpack(bags and bags.freeKnown and bags.free <= 3 and GOLD or MUTED))
    U.freeSlotsIcon:SetVertexColor(unpack(bags and bags.freeKnown and bags.free <= 3 and GOLD or MUTED))
    if bags then
        fitMoney(U.bagValue, (bags.pending > 0 and ">= " or "") .. U.Money(bags.value))
        U.bagStatus:SetText(bags.pending > 0 and ("Loading: " .. bags.pending) or (bags.stacks .. " stacks / " .. U.Number(bags.items)))
    end
    fitMoney(U.soldValue, (A.db.vendorSalesPartial and ">= " or "") .. U.Money(A.db.vendorSales))
    U.lock.label:SetText(A.db.locked and "Unlock" or "Lock")
    U.panel:SetShown(not A.db.hidden)
    U.RefreshLevels()
end
