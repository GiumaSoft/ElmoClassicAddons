function U.RefreshLevels()
    if not U.levelPanel then return end
    local expanded = A.db.levelExpanded
    U.levelPanel:SetShown(expanded)
    if U.levelExpanded ~= expanded then
        local left, top = U.panel:GetLeft(), U.panel:GetTop()
        U.panel:SetSize(WIDTH, HEIGHT + (expanded and DETAILS_HEIGHT or 0))
        if (U.levelExpanded ~= nil or expanded) and left and top then
            U.panel:ClearAllPoints(); U.panel:SetPoint("TOPLEFT", UIParent, "TOPLEFT", left - UIParent:GetLeft(), top - UIParent:GetTop())
        end
        local direction = expanded and -1 or 1
        U.chevrons[1]:SetStartPoint("CENTER", U.levelToggle, 19, 2 * direction)
        U.chevrons[1]:SetEndPoint("CENTER", U.levelToggle, 23, -2 * direction)
        U.chevrons[2]:SetStartPoint("CENTER", U.levelToggle, 23, -2 * direction)
        U.chevrons[2]:SetEndPoint("CENTER", U.levelToggle, 27, 2 * direction)
        U.levelExpanded = expanded
    end
    local state, count = A.db.levelState, #A.db.levels + 1
    U.levelOffset = math.min(U.levelOffset, math.max(0, count - ROWS))
    for i, row in ipairs(U.levelRows) do
        local index = U.levelOffset + i
        local current = index == 1
        local entry = current and state or A.db.levels[index - 1]
        row.entry = entry; row:SetShown(entry ~= nil)
        if entry then
            local atCap = current and U.progress and U.progress.capped
            row.level:SetText(current and (entry.level .. (atCap and "" or (" -> " .. (entry.level + 1)))) or (entry.from .. " -> " .. entry.to))
            local seconds = current and A.Levels.CurrentSeconds() or entry.seconds
            row.duration:SetText(atCap and "--" or (A.IsNumber(seconds) and U.SessionTime(seconds) or "--"))
            row.status:SetText(atCap and "Max level" or (current and (entry.complete and "In progress" or "Partial") or
                (not seconds and "Unavailable" or (entry.complete and "Complete" or "Partial"))))
            row.duration:SetTextColor(unpack(current and GOLD or {.914, .894, .843}))
            row.dot:SetColorTexture(unpack(current and GOLD or {.46, .41, .30}))
        end
    end
    U.levelPage:SetText((U.levelOffset + 1) .. "-" .. math.min(count, U.levelOffset + ROWS) .. " / " .. count)
    U.levelUp:SetShown(count > ROWS); U.levelDown:SetShown(count > ROWS)
end

function U.ReadProgress()
    local actual = A.Call(UnitLevel, "player")
    actual = A.IsNumber(actual) and actual or 0
    local result = {level = math.max(actual, A.expectedLevel or 0, A.last and A.last.level or 0)}
    local xp, maximum = A.Call(UnitXP, "player"), A.Call(UnitXPMax, "player")
    if result.level < 1 or not A.IsNumber(maximum) or actual < result.level then return result end
    if maximum == 0 then result.capped, result.fraction = true, 1; return result end
    if not A.IsNumber(xp) or xp > maximum then return result end
    result.fraction, result.remaining, result.maximum = xp / maximum, maximum - xp, maximum
    if type(GetXPExhaustion) == "function" then
        local ok, rested = pcall(GetXPExhaustion)
        if ok and rested == nil then rested = 0 end
        if ok and A.IsNumber(rested) then result.rested = rested / maximum end
    end
    return result
end
function U.ProgressText()
    local progress = U.progress
    if progress.capped then return "Maximum level" end
    if progress.remaining then return U.Number(progress.remaining) .. " XP to level " .. (progress.level + 1) end
    return "XP unavailable"
end
local function fillRing(arc, fraction)
    if arc.radial then
        arc.radial:SetRadialProgressBarPercent(fraction); arc.radial:SetShown(fraction > 0)
        return
    end
    for i, part in ipairs(arc) do
        local amount = math.max(0, math.min(1, fraction * 4 - (i - 1)))
        part.texture:SetShown(amount > 0)
        if part.masked then part.texture:RemoveMaskTexture(part.mask); part.masked = false end
        if amount > 0 and amount < 1 then
            -- A rotating half-plane cuts only the current quadrant. The
            -- annulus itself stays a continuous, antialiased texture.
            local angle = (4 - i - amount) * math.pi / 2
            local nx, ny = math.cos(angle), math.sin(angle)
            local left, top = QUADRANTS[i][2] - .5, .5 - QUADRANTS[i][3]
            local upperLeft = .5 + nx * left + ny * top
            local lowerLeft = upperLeft - ny / 2
            local upperRight = upperLeft + nx / 2
            part.mask:SetTexCoord(0, upperLeft, 0, lowerLeft, 1, upperRight, 1, upperRight - ny / 2)
            part.texture:AddMaskTexture(part.mask); part.masked = true
        end
    end
end
function U.RefreshRing(progress)
    if U.ringFraction == progress.fraction and U.ringRested == progress.rested then return end
    U.ringFraction, U.ringRested = progress.fraction, progress.rested
    local fraction = progress.fraction or 0
    fillRing(U.restedRing, progress.rested and progress.rested > 0 and math.min(1, fraction + progress.rested) or 0)
    fillRing(U.earnedRing, fraction)
end
local function createRing(color, layer)
    local arc = {}
    local whole = U.signet:CreateTexture(nil, "ARTWORK", nil, layer)
    whole:SetAllPoints(); whole:SetTexture(RING); whole:SetVertexColor(unpack(color)); whole:Hide(); smooth(whole)
    -- New clients can clip a single continuous texture in the renderer.
    if type(whole.SetRadialProgressBarPercent) == "function" then
        whole:SetRadialProgressBarReverse(false); whole:SetRadialProgressBarFeather(.002)
        arc.radial = whole
        return arc
    end
    -- Classic Era has no radial shader. Keep all cropped regions and masks
    -- unsharpened, as with TomTom/Questie's scalable textures.
    for i, quadrant in ipairs(QUADRANTS) do
        local texture = i == 1 and whole or U.signet:CreateTexture(nil, "ARTWORK", nil, layer)
        texture:ClearAllPoints(); texture:SetSize(38, 38); texture:SetPoint(quadrant[1]); texture:SetTexture(RING)
        texture:SetTexCoord(quadrant[2], quadrant[2] + .5, quadrant[3], quadrant[3] + .5)
        texture:SetVertexColor(unpack(color)); texture:Hide(); smooth(texture)
        local mask = U.signet:CreateMaskTexture()
        mask:SetAllPoints(texture)
        mask:SetTexture("Interface\\AddOns\\ElmoLeveling\\Media\\RingMask.tga", "CLAMPTOBLACKADDITIVE", "CLAMPTOBLACKADDITIVE")
        smooth(mask)
        arc[i] = {texture = texture, mask = mask}
    end
    return arc
end
